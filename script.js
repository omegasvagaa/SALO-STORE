function createBackgroundParticles(width, height, compact) {
  const leaves = compact ? 6 : 16;
  const dust = compact ? 14 : Math.min(68, Math.max(30, Math.round((width * height) / 26000)));
  return Array.from({ length: leaves + dust }, (_, index) => {
    const kind = index < leaves ? 'leaf' : 'dust';
    const depth = .48 + Math.random() * .82;
    return {
      kind,
      x: Math.random() * width,
      y: Math.random() * height,
      size: kind === 'leaf' ? (9 + Math.random() * 5) * depth : Math.random() * 1.45 + .35,
      speed: kind === 'leaf' ? .11 + Math.random() * .18 : Math.random() * .12 + .025,
      phase: Math.random() * Math.PI * 2,
      angle: Math.random() * Math.PI * 2,
      spin: (Math.random() * .7 + .16) * (Math.random() < .5 ? -1 : 1),
      alpha: kind === 'leaf' ? .48 + Math.random() * .22 : Math.random() * .3 + .08,
      depth,
      colorIndex: Math.floor(Math.random() * 3)
    };
  });
}
