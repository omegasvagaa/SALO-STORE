function getStoredValue(key) {
  try { return localStorage.getItem(key); } catch (_) { return null; }
}
function storeValue(key, value) {
  try { localStorage.setItem(key, value); } catch (_) { /* Storage may be unavailable. */ }
}
function getText(dictionary, path) {
  return path.split('.').reduce((value, part) => value && value[part], dictionary);
}
function setTheme(theme, persist) {
  const safeTheme = theme === 'light' ? 'light' : 'dark';
  root.dataset.theme = safeTheme;
  const dictionary = translations[currentLanguage];
  if (themeName) themeName.textContent = dictionary.theme[safeTheme];
  if (themeButton) {
    const label = dictionary.theme[safeTheme === 'dark' ? 'switchToLight' : 'switchToDark'];
    themeButton.setAttribute('aria-label', label);
    themeButton.title = label;
  }
  const themeColor = document.getElementById('theme-color-meta');
  if (themeColor) themeColor.content = safeTheme === 'light' ? '#F5EEE3' : '#0D0908';
  if (persist) storeValue('theme', safeTheme);
}
function animateSystemSignal() {
  const value = document.querySelector('[data-system-signal-value]');
  const progress = document.querySelector('.progress[role="progressbar"]');
  const fill = document.querySelector('[data-system-signal-fill]');
  if (!value || !progress || !fill) return;

  const target = 78;
  const duration = 1800;
  const setValue = (percent) => {
    const rounded = Math.round(percent);
    value.textContent = rounded + '%';
    progress.setAttribute('aria-valuenow', String(rounded));
    fill.style.transform = 'scaleX(' + (percent / 100) + ')';
  };

  if (reducedMotion) {
    setValue(target);
    return;
  }

  const start = performance.now();
  const render = (now) => {
    const progressRatio = Math.min(1, (now - start) / duration);
    const eased = 1 - Math.pow(1 - progressRatio, 3);
    setValue(target * eased);
    if (progressRatio < 1) window.requestAnimationFrame(render);
  };

  setValue(0);
  window.requestAnimationFrame(render);
}
function updatePurchaseLinks(language) {
  const dictionary = translations[language];
  document.querySelectorAll('[data-purchase-plan]').forEach((link) => {
    const plan = dictionary.plans[link.dataset.purchasePlan];
    if (!plan) return;
    const message = [
      dictionary.telegram.greeting, '',
      dictionary.telegram.planLabel + ': ' + plan.name,
      dictionary.telegram.priceLabel + ': ' + plan.price,
      dictionary.telegram.durationLabel + ': ' + plan.duration,
      ...(plan.bonus ? [dictionary.telegram.bonusLabel + ': ' + plan.bonus] : []),
      '',
      dictionary.telegram.closing
    ].join('\n');
    link.href = 'https://t.me/pssalo?text=' + encodeURIComponent(message);
  });
}
function applyLanguage(language, persist) {
  const safeLanguage = language === 'ru' ? 'ru' : 'en';
  const dictionary = translations[safeLanguage];
  currentLanguage = safeLanguage;
  root.lang = safeLanguage;
  root.dataset.language = safeLanguage;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = getText(dictionary, element.dataset.i18n);
    if (typeof value === 'string') element.textContent = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = getText(dictionary, element.dataset.i18nHtml);
    if (typeof value === 'string') element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    element.dataset.i18nAttr.split(';').forEach((pair) => {
      const parts = pair.split(':').map((part) => part.trim());
      const value = parts[1] && getText(dictionary, parts[1]);
      if (parts[0] && typeof value === 'string') element.setAttribute(parts[0], value);
    });
  });
  Object.entries(dictionary.plans).forEach(([key, plan]) => {
    const selectors = {
      name: '[data-plan-name="' + key + '"]',
      tag: '[data-plan-tag="' + key + '"]',
      shortDuration: '[data-plan-short-duration="' + key + '"]',
      price: '[data-plan-price="' + key + '"]',
      period: '[data-plan-period="' + key + '"]'
    };
    Object.entries(selectors).forEach(([field, selector]) => {
      const element = document.querySelector(selector);
      if (element) element.textContent = plan[field];
    });
  });
  languageButtons.forEach((button) => button.setAttribute('aria-pressed', String(button.dataset.language === safeLanguage)));
  setTheme(root.dataset.theme || 'dark', false);
  updatePurchaseLinks(safeLanguage);
  if (menuButton) {
    const label = dictionary.aria[header && header.classList.contains('is-menu-open') ? 'closeMenu' : 'openMenu'];
    menuButton.setAttribute('aria-label', label);
  }
  document.title = dictionary.meta.title;
  if (persist) storeValue('language', safeLanguage);
}
function closeMenu() {
  if (!header || !menuButton) return;
  header.classList.remove('is-menu-open');
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', translations[currentLanguage].aria.openMenu);
}
function toggleMenu() {
  if (!header || !menuButton) return;
  const open = !header.classList.contains('is-menu-open');
  header.classList.toggle('is-menu-open', open);
  menuButton.setAttribute('aria-expanded', String(open));
  menuButton.setAttribute('aria-label', translations[currentLanguage].aria[open ? 'closeMenu' : 'openMenu']);
}
