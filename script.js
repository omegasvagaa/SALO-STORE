  const nx = Math.max(-1, Math.min(1, ((clientX - bounds.left) / bounds.width) * 2 - 1));
  const ny = Math.max(-1, Math.min(1, ((clientY - bounds.top) / bounds.height) * 2 - 1));
  entity.target.rotateX = -ny * entity.strength;
  entity.target.rotateY = nx * entity.strength;
  entity.target.shiftX = nx * entity.shift;
  entity.target.shiftY = ny * entity.shift;
  entity.target.scale = entity.scaleTarget;
  entity.target.lightX = (nx + 1) * 50;
  entity.target.lightY = (ny + 1) * 50;
  entity.target.contentX = nx * entity.content;
  entity.target.contentY = ny * entity.content * .72;
  entity.active = true;
  entity.element.classList.add('is-pointer-active');
  entity.element.classList.add('is-light-active');
