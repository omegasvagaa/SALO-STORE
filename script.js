function animate(now) {
  const dt = Math.min((now - (previousFrame || now)) / 1000, .04);
  previousFrame = now;
  if (motionEffectsEnabled) {
    const globalResultX = spring(globalPointer.x, globalVelocity.x, globalTarget.x, dt, 26, 11);
    const globalResultY = spring(globalPointer.y, globalVelocity.y, globalTarget.y, dt, 26, 11);
    globalPointer.x = globalResultX[0]; globalVelocity.x = globalResultX[1];
    globalPointer.y = globalResultY[0]; globalVelocity.y = globalResultY[1];
    root.style.setProperty('--pointer-x', (globalPointer.x * 100).toFixed(2) + '%');
    root.style.setProperty('--pointer-y', (globalPointer.y * 100).toFixed(2) + '%');
    root.style.setProperty('--grid-shift-x', ((globalPointer.x - .5) * -17).toFixed(2) + 'px');
    root.style.setProperty('--grid-shift-y', ((globalPointer.y - .5) * -17).toFixed(2) + 'px');
    tiltEntities.forEach((entity) => renderEntity(entity, dt, now));
  }
  renderCounters(now);
  if (particleContext && !document.hidden) {
    particleContext.clearRect(0, 0, canvasWidth, canvasHeight);
    const palette = getParticlePalette();
    const parallaxX = motionEffectsEnabled ? (globalPointer.x - .5) * 16 : 0;
    const parallaxY = Math.sin(window.scrollY * .001) * 8;
    backgroundParticles.forEach((particle) => {
      if (particle.kind === 'leaf') {
        particle.phase += particle.speed * dt * 60;
        particle.y += particle.speed * particle.depth * dt * 65;
        particle.angle += particle.spin * dt;
        if (particle.y > canvasHeight + 12) { particle.y = -12; particle.x = Math.random() * canvasWidth; }
      } else {
        particle.phase += particle.speed * dt * 60;
        particle.y -= particle.speed * dt * 22;
        if (particle.y < -5) { particle.y = canvasHeight + 5; particle.x = Math.random() * canvasWidth; }
      }
      const x = particle.x + Math.sin(particle.phase) * (particle.kind === 'leaf' ? 9 * particle.depth : 4) + parallaxX;
      const y = particle.y + (particle.kind === 'leaf' ? 0 : Math.cos(particle.phase * .8) * 3) + parallaxY;
      const color = palette[particle.colorIndex];
      particleContext.save();
      particleContext.globalAlpha = particle.alpha * (particle.kind === 'leaf' ? particle.depth : 1);
      particleContext.fillStyle = color;
      particleContext.strokeStyle = color;
      particleContext.shadowColor = color;
      particleContext.shadowBlur = particle.kind === 'leaf' ? 7 * particle.depth : (particle.size > 1.2 ? 7 : 3);
      if (particle.kind === 'leaf') {
        particleContext.translate(x, y);
        particleContext.rotate(particle.angle + Math.sin(particle.phase) * .16);
        particleContext.scale(1, .72);
        particleContext.beginPath();
        particleContext.moveTo(0, -particle.size);
        particleContext.quadraticCurveTo(particle.size * 1.15, -particle.size * .32, 0, particle.size);
        particleContext.quadraticCurveTo(-particle.size * 1.15, -particle.size * .32, 0, -particle.size);
        particleContext.fill();
        particleContext.lineWidth = Math.max(.55, particle.size * .06);
        particleContext.stroke();
        particleContext.beginPath();
        particleContext.moveTo(0, -particle.size * .72);
        particleContext.lineTo(0, particle.size * .72);
        particleContext.stroke();
      } else {
        particleContext.beginPath();
        particleContext.arc(x, y, particle.size, 0, Math.PI * 2);
        particleContext.fill();
      }
      particleContext.restore();
    });
    particleContext.shadowBlur = 0;
  }
  if (!document.hidden) rafId = window.requestAnimationFrame(animate);
}
